const SHEET_SELECT =
  '*, work_orders(id, work_order_number, wo_status)';

/** Legal Measurement Book moves. Mirrors ms_transition_allowed(). */
const MS_TRANSITIONS: Record<MeasurementSheetStatus, MeasurementSheetStatus[]> = {
  draft: ['submitted'],
  submitted: ['verified', 'rejected', 'draft'],
  // A verified sheet can only be pulled back to submitted, and the database
  // refuses even that once a certified bill relies on it.
  verified: ['submitted'],
  rejected: ['draft', 'submitted'],
};

export function nextMeasurementSheetStatuses(
  current: string | null | undefined,
  canVerify: boolean,
): MeasurementSheetStatus[] {
  const key = (current ?? '').trim().toLowerCase() as MeasurementSheetStatus;
  const options = MS_TRANSITIONS[key] ?? [];
  return options.filter((next) => canVerify || (next !== 'verified' && next !== 'rejected'));
}

