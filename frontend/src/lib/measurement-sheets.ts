// ============================================================================
// PRAMUKH GROUP ERP V2 — MEASUREMENT BOOK
// File: frontend/src/lib/measurement-sheets.ts
//
// Site-recorded quantities that justify an RA bill. A VERIFIED sheet is a hard
// prerequisite for certifying a service bill (trg_service_bill_evidence_gate),
// unless the project sets budget_config.sb_measurement_enforcement = warn_only.
//
// Quantities are never computed here: measurement_sheet_items.total_quantity is
// a generated column (nos x L x W x H - deduction, floored at zero) and the
// sheet header rolls up from a trigger. The figures shown in the UI are a
// preview of what the server will store, never an independent calculation.
// ============================================================================

import { supabase, getDbSiteId } from '@/utils/supabase-client';
import { isLiveSupabase } from '@/lib/erp/supabase-modules';

type MutationResult<T = unknown> = { data: T | null; error: Error | null };

function asError(error: unknown): Error {
  return error instanceof Error ? error : new Error(String(error));
}

/** Guard messages are written for the person reading the screen. */
function asDbError(error: { message?: string; code?: string; hint?: string | null } | null): Error {
  if (!error) return new Error('Unknown database error.');
  const message = error.message || 'The database rejected this change.';
  if (error.hint && (error.code === '22023' || error.code === '23514')) {
    return new Error(`${message} ${error.hint}`);
  }
  return new Error(message);
}

